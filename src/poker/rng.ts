export type Rng = () => number;

/** Small seedable PRNG (mulberry32) so simulations are reproducible in tests. */
export function seeded(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export const defaultRng: Rng = Math.random;

export function pick<T>(a: readonly T[], rng: Rng = defaultRng): T {
  return a[(rng() * a.length) | 0];
}

export function shuffle<T>(a: T[], rng: Rng = defaultRng): T[] {
  for (let i = a.length - 1; i > 0; i--) {
    const j = (rng() * (i + 1)) | 0;
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
